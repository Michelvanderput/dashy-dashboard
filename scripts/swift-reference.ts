/**
 * Reference data for the Swift port: recordings of the TypeScript simulation (core.ts, small.ts, driver.ts).
 * The Swift tests replay the same inputs and must reproduce these numbers.
 *   npm run swift:reference
 */
import { writeFileSync } from 'node:fs';
import { createDashy, type DashyState, type Geometry, type Shape } from '../src/core';
import { RULES, initialDriverState, nextWakeAt, reduce, resolve, type DriverEvent } from '../src/driver';
import { smallGeometry } from '../src/small';

export const REFERENCE_PATH = 'swift/DashyKit/Tests/DashyKitTests/Resources/reference.json';
const STATES: DashyState[] = ['idle', 'received', 'working', 'thinking', 'waiting', 'blocked', 'done', 'happy', 'sad', 'angry', 'strict', 'dancing', 'sleepy'];

/** Flat, fixed order, so Swift can compare element by element: rx, body(5), face(5), then per eye x y tilt ew eh cov lidA low blink. */
export const flat = (G: Geometry): number[] => [
  G.rx, G.body.tx, G.body.ty, G.body.rot, G.body.sx, G.body.sy, G.face.tx, G.face.ty, G.face.rot, G.face.sx, G.face.sy,
  ...G.eyes.flatMap(e => [e.x, e.y, e.tilt, e.ew, e.eh, e.cov, e.lidA, e.low, e.blink]),
];

function simulation(state: DashyState, shape: Shape) {
  const d = createDashy({ seed: 7 }); d.setShape(shape); d.setState(state, 0);
  const frames: { t: number; cur: string; g: number[]; small: number[] }[] = [];
  let i = 0;
  for (let ms = 0; ms < 30000; ms += 16.67, i++) {
    const a = ms / 1000; d.pointer(Math.sin(a * 1.3) * 1.4, Math.cos(a * .9) * 1.4, ms);
    const G = d.step(ms);
    if (i % 30 === 0) frames.push({ t: ms, cur: G.cur, g: flat(G), small: flat(smallGeometry(G)) });
  }
  return { state, shape, seed: 7, frames };
}

function extras() {
  // received -> working and done -> idle, state name every 100 frames
  const d = createDashy({ seed: 2 }); d.setState('idle', 0);
  const names: [number, string][] = []; let ms = 0, i = 0;
  const run = (until: number) => { for (; ms < until; ms += 16.67, i++) { const G = d.step(ms); if (i % 20 === 0) names.push([ms, G.cur]); } };
  run(300); d.setState('received', ms); run(ms + 900); d.setState('done', ms); run(ms + 3800);
  // eyeScale 1, settled idle
  const e = createDashy({ seed: 4, eyeScale: 1 }); let G!: Geometry;
  for (let t = 0; t < 3000; t += 16.67) { e.pointer(0, 0, t); G = e.step(t); }
  // a long pause
  const p = createDashy({ seed: 7 }); p.setState('dancing', 0); let t2 = 0; for (; t2 < 1000; t2 += 16.67) p.step(t2);
  const pause = flat(p.step(t2 + 30000));
  // blinks in 60 s
  const blinks = Object.fromEntries((['idle', 'angry', 'sleepy', 'working'] as DashyState[]).map(s => {
    const b = createDashy({ seed: 3 }); b.setState(s, 0); let n = 0, inb = false;
    for (let t = 0; t < 60000; t += 16.67) { const x = b.step(t).eyes[0].blink > .5; if (x && !inb) n++; inb = x; }
    return [s, n];
  }));
  return { receivedDone: names, eyeScale1: flat(G), pause, blinks };
}

function driverStorm() {
  const MIN = 60_000, T0 = 1_000_000;
  let seed = 42; const rnd = () => (seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296;
  const ids = ['a', 'b', 'c'];
  const make = (): DriverEvent => {
    const id = ids[Math.floor(rnd() * 3)], r = rnd();
    if (r < .2) return { type: 'taskAdded', id, dueAt: rnd() < .7 ? T0 + Math.floor(rnd() * 180) * MIN : null };
    if (r < .35) return { type: 'taskDone', id };
    if (r < .4) return { type: 'taskRemoved', id };
    if (r < .5) return { type: 'taskDueChanged', id, dueAt: T0 + Math.floor(rnd() * 180) * MIN };
    const flag = ['waiting', 'blocked', 'break', 'working'][Math.floor(rnd() * 4)] as 'waiting';
    return r < .9 ? { type: flag, value: rnd() < .5 } : { type: 'activity' };
  };
  let s = initialDriverState(T0), now = T0;
  const steps: { t: number; event: DriverEvent; rule: string; state: string; wake: number | null; later: { rule: string; state: string } }[] = [];
  for (let i = 0; i < 800; i++) {
    now += Math.floor(rnd() * 5 * MIN);
    const event = make(); s = reduce(s, event, now);
    const r = resolve(s, now), later = resolve(s, now + 90 * MIN);
    steps.push({ t: now, event, rule: r.rule, state: r.state, wake: nextWakeAt(s, now), later: { rule: later.rule, state: later.state } });
  }
  return { start: T0, steps, rules: RULES };
}

export function buildReference() {
  return {
    note: 'Generated by scripts/swift-reference.ts from core.ts, small.ts and driver.ts. Do not edit; run npm run swift:reference.',
    simulations: (['square', 'circle'] as Shape[]).flatMap(shape => STATES.map(s => simulation(s, shape))),
    extras: extras(),
    driver: driverStorm(),
  };
}

if (process.argv[1]?.endsWith('swift-reference.ts')) {
  writeFileSync(REFERENCE_PATH, JSON.stringify(buildReference()));
  console.log(`wrote ${REFERENCE_PATH}`);
}
